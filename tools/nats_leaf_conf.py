#!/usr/bin/env python3
"""Generate nats-server configs for a fly.board site cluster (leafnodes).

The sites are listed in the same failover order as flywire.settings nodes=.
The first site is the hub; every other site joins it as a leaf node. The
second site also accepts leaf connections, and the remaining sites list it as
their fallback remote, so when the hub dies they reconnect to the second site
and the survivors stay connected (a <-> b). When the hub returns, the second
site rejoins it and the chain is whole again:

    normal:          hub dead:         hub back:
      n1               (n1)               n1
     /  \\                                 |
    n2   n3          n2 -- n3            n2 -- n3

Leaf links use TLS with a cluster-private CA (sites are addressed by IP, so
the certificates carry IP SANs) and a shared leaf password. Each site keeps
its client port on loopback for fly_board (NATS_URL=nats://127.0.0.1:4222).

  tools/nats_leaf_conf.py init-ca DIR
  tools/nats_leaf_conf.py issue DIR ADDR            # cert for a hub site
  tools/nats_leaf_conf.py conf --nodes A,B,C --self B --secret S \\
        --tls-dir /etc/nats/tls > /etc/nats-server.conf

A node may be written ADDR or ADDR:LEAFPORT (default 7422); --client-port
overrides this site's client port (local multi-node tests).
"""

import argparse
import ipaddress
import os
import subprocess
import sys

LEAF_USER = "flyleaf"
DEFAULT_LEAF_PORT = 7422


def split_node(node):
    host, sep, port = node.rpartition(":")
    if sep and port.isdigit() and host and not host.endswith("]"):
        return host, int(port)
    return node, DEFAULT_LEAF_PORT


def run(cmd):
    subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)


def init_ca(d):
    os.makedirs(d, exist_ok=True)
    key, crt = os.path.join(d, "ca.key"), os.path.join(d, "ca.pem")
    if os.path.exists(key):
        sys.exit(f"{key} exists; refusing to overwrite the cluster CA")
    run(["openssl", "req", "-x509", "-newkey", "ec", "-pkeyopt", "ec_paramgen_curve:prime256v1",
         "-nodes", "-keyout", key, "-out", crt, "-days", "3650", "-subj", "/CN=fly.board NATS leaf CA"])
    os.chmod(key, 0o600)
    print(f"wrote {crt} and {key} (keep ca.key off the sites)")


def issue(d, addr):
    host, _ = split_node(addr)
    try:
        ipaddress.ip_address(host)
        san = f"IP:{host}"
    except ValueError:
        san = f"DNS:{host}"
    base = os.path.join(d, host)
    ext = base + ".ext"
    with open(ext, "w") as f:
        f.write(f"subjectAltName={san}\nextendedKeyUsage=serverAuth,clientAuth\n")
    try:
        run(["openssl", "req", "-newkey", "ec", "-pkeyopt", "ec_paramgen_curve:prime256v1", "-nodes",
             "-keyout", base + ".key", "-out", base + ".csr", "-subj", f"/CN={host}"])
        run(["openssl", "x509", "-req", "-in", base + ".csr", "-CA", os.path.join(d, "ca.pem"),
             "-CAkey", os.path.join(d, "ca.key"), "-CAcreateserial", "-out", base + ".pem",
             "-days", "825", "-extfile", ext])
    finally:
        for p in (ext, base + ".csr"):
            if os.path.exists(p):
                os.remove(p)
    os.chmod(base + ".key", 0o600)
    print(f"wrote {base}.pem and {base}.key")


def conf(nodes, self_node, secret, tls_dir, client_port):
    if self_node not in nodes:
        sys.exit(f"--self {self_node} is not in --nodes")
    if len(nodes) < 2:
        sys.exit("need at least two nodes")
    me = nodes.index(self_node)
    host, leaf_port = split_node(self_node)
    ca = os.path.join(tls_dir, "ca.pem")
    out = [
        "# Generated by tools/nats_leaf_conf.py - fly.board leafnode topology.",
        f"# Sites in failover order: {', '.join(nodes)}; this is {self_node}.",
        f"server_name: \"{host if leaf_port == DEFAULT_LEAF_PORT else f'{host}-{leaf_port}'}\"",
        f"listen: 127.0.0.1:{client_port}",
        "",
        "leafnodes {",
    ]
    if me <= 1:
        role = "hub" if me == 0 else "fallback hub"
        out += [
            f"  # {role}: accepts leaf connections",
            f"  listen: 0.0.0.0:{leaf_port}",
            "  # Advertise the site address, not every local interface: leaves",
            "  # would otherwise also dial private IPs that cannot pass TLS.",
            f"  advertise: \"{host}:{leaf_port}\"",
            "  tls {",
            f"    cert_file: \"{os.path.join(tls_dir, host + '.pem')}\"",
            f"    key_file: \"{os.path.join(tls_dir, host + '.key')}\"",
            f"    ca_file: \"{ca}\"",
            "    timeout: 5",
            "  }",
            "  authorization {",
            f"    user: \"{LEAF_USER}\"",
            f"    password: \"{secret}\"",
            "  }",
        ]
    if me >= 1:
        # The hub first; the fallback hub for everyone but the fallback itself.
        targets = [nodes[0]] + ([nodes[1]] if me >= 2 else [])
        urls = []
        for t in targets:
            th, tp = split_node(t)
            urls.append(f"\"nats-leaf://{LEAF_USER}:{secret}@{th}:{tp}\"")
        out += [
            "  remotes [",
            "    {",
            f"      urls: [{', '.join(urls)}]",
            "      # Try the hub first; the fallback hub is dialed only when the",
            "      # hub is down (the default would shuffle the list).",
            "      no_randomize: true",
            "      tls {",
            f"        ca_file: \"{ca}\"",
            "        timeout: 5",
            "      }",
            "    }",
            "  ]",
            "  reconnect: \"2s\"",
        ]
    out.append("}")
    print("\n".join(out))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("init-ca")
    a.add_argument("dir")
    b = sub.add_parser("issue")
    b.add_argument("dir")
    b.add_argument("addr")
    c = sub.add_parser("conf")
    c.add_argument("--nodes", required=True, help="comma-separated, failover order (as flywire nodes=)")
    c.add_argument("--self", dest="self_node", required=True)
    c.add_argument("--secret", required=True, help="shared leaf password")
    c.add_argument("--tls-dir", required=True, help="directory holding ca.pem and <addr>.pem/.key")
    c.add_argument("--client-port", type=int, default=4222)
    args = ap.parse_args()
    if args.cmd == "init-ca":
        init_ca(args.dir)
    elif args.cmd == "issue":
        issue(args.dir, args.addr)
    else:
        nodes = [n.strip().rstrip("/") for n in args.nodes.split(",") if n.strip()]
        conf(nodes, args.self_node, args.secret, args.tls_dir, args.client_port)


if __name__ == "__main__":
    main()
